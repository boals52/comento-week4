baseline_accumulator = (
    metrics_utils.DepthMetricAccumulator()
)

baseline_per_image_records = []

sample_offset = 0
evaluation_start = time.time()

progress_bar = tqdm(
    test_loader,
    desc="Baseline evaluation — 518×518",
    unit="batch",
)

with torch.inference_mode():
    for batch in progress_bar:
        images = batch["image"]

        target_depth = batch["depth"].to(
            config_utils.DEVICE,
            non_blocking=True,
        )

        valid_mask = batch["valid_mask"].to(
            config_utils.DEVICE,
            non_blocking=True,
        )

        baseline_prediction = (
            inference_utils.predict_depth_batch(
                model=baseline_model,
                images=images,
                image_processor=baseline_processor,
                device=config_utils.DEVICE,
                target_size=target_depth.shape[-2:],
                clamp_depth=True,
                min_depth=config_utils.MIN_DEPTH,
                max_depth=config_utils.MAX_DEPTH,
            )
        )

        # 전체 픽셀 기준 지표 누적
        baseline_accumulator.update(
            predicted_depth=baseline_prediction,
            target_depth=target_depth,
            valid_mask=valid_mask,
            min_depth=config_utils.MIN_DEPTH,
            max_depth=config_utils.MAX_DEPTH,
            clamp_prediction=True,
        )

        batch_size = images.shape[0]
        metadata = batch.get("metadata", {})

        for batch_index in range(batch_size):
            sample_index = (
                sample_offset + batch_index
            )

            sample_prediction = baseline_prediction[
                batch_index:
                batch_index + 1
            ]

            sample_target = target_depth[
                batch_index:
                batch_index + 1
            ]

            sample_mask = valid_mask[
                batch_index:
                batch_index + 1
            ]

            sample_metrics = (
                metrics_utils.calculate_depth_metrics(
                    predicted_depth=sample_prediction,
                    target_depth=sample_target,
                    valid_mask=sample_mask,
                    min_depth=config_utils.MIN_DEPTH,
                    max_depth=config_utils.MAX_DEPTH,
                    clamp_prediction=True,
                )
            )

            prediction_path = (
                BASELINE_PREDICTION_DIR
                / (
                    f"sample_{sample_index:03d}"
                    "_pred_baseline.npy"
                )
            )

            np.save(
                prediction_path,
                sample_prediction[
                    0,
                    0,
                ]
                .detach()
                .cpu()
                .numpy()
                .astype(np.float32),
            )

            record = {
                "sample_index": sample_index,
                "prediction_path": str(
                    prediction_path
                ),
                **sample_metrics,
            }

            if isinstance(metadata, dict):
                for metadata_key in [
                    "sequence",
                    "frame",
                    "rgb_path",
                    "depth_path",
                ]:
                    if metadata_key not in metadata:
                        continue

                    metadata_value = metadata[
                        metadata_key
                    ]

                    if isinstance(
                        metadata_value,
                        (list, tuple),
                    ):
                        record[metadata_key] = (
                            metadata_value[
                                batch_index
                            ]
                        )
                    else:
                        record[metadata_key] = (
                            metadata_value
                        )

            baseline_per_image_records.append(
                record
            )

        sample_offset += batch_size

        progress_bar.set_postfix(
            samples=sample_offset,
        )


baseline_evaluation_seconds = (
    time.time() - evaluation_start
)

