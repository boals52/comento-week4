# Plotly용 RGB 색상 변환 함수
def rgb_array_to_plotly_colors(
    colors: np.ndarray,
) -> list[str]:
    """
    [N, 3] RGB 배열을 Plotly용 rgb(r, g, b) 문자열로 변환합니다.

    입력값이 0~1 범위이면 0~255로 변환합니다.
    """

    colors = np.asarray(
        colors,
        dtype=np.float32,
    )

    if colors.ndim != 2 or colors.shape[1] != 3:
        raise ValueError(
            "colors must have shape [N, 3]. "
            f"Received: {colors.shape}"
        )

    if colors.max() <= 1.0:
        colors = colors * 255.0

    colors = np.clip(
        colors,
        0,
        255,
    ).astype(np.uint8)

    return [
        f"rgb({red},{green},{blue})"
        for red, green, blue in colors
    ]

# Point Cloud 개수 축소 함수
# 최대 점 개수를 제한
def subsample_point_cloud(
    points: np.ndarray,
    colors: np.ndarray,
    max_points: int = 40000,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Point Cloud가 너무 큰 경우 균일 간격으로 일부 점만 선택합니다.
    """

    if len(points) != len(colors):
        raise ValueError(
            "points와 colors의 개수가 일치해야 합니다."
        )

    if len(points) <= max_points:
        return points, colors

    indices = np.linspace(
        0,
        len(points) - 1,
        max_points,
        dtype=np.int64,
    )

    return (
        points[indices],
        colors[indices],
    )

