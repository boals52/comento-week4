# point cloud 생성
def depth_to_pseudo_point_cloud(
    depth,
    rgb,
    min_depth=0.1,
    max_depth=80.0,
    stride=2,
    focal_length=None,
):
    """
    518×518 depth map을 근사 카메라 파라미터로
    pseudo point cloud로 변환합니다.
    """

    if depth.ndim != 2:
        raise ValueError(
            f"depth must be [H, W], received {depth.shape}"
        )

    if rgb.ndim != 3 or rgb.shape[2] != 3:
        raise ValueError(
            f"rgb must be [H, W, 3], received {rgb.shape}"
        )

    height, width = depth.shape

    if rgb.shape[:2] != depth.shape:
        raise ValueError(
            "RGB와 depth 해상도가 일치하지 않습니다."
        )

    if focal_length is None:
        focal_length = float(max(height, width))

    fx = focal_length
    fy = focal_length
    cx = (width - 1) / 2.0
    cy = (height - 1) / 2.0

    v, u = np.mgrid[
        0:height:stride,
        0:width:stride,
    ]

    sampled_depth = depth[
        0:height:stride,
        0:width:stride,
    ]

    sampled_rgb = rgb[
        0:height:stride,
        0:width:stride,
    ]

    valid = (
        np.isfinite(sampled_depth)
        & (sampled_depth >= min_depth)
        & (sampled_depth <= max_depth)
    )

    z = sampled_depth[valid]

    x = (
        (u[valid] - cx)
        * z
        / fx
    )

    y = (
        (v[valid] - cy)
        * z
        / fy
    )

    points = np.stack(
        [x, y, z],
        axis=1,
    ).astype(np.float32)

    colors = sampled_rgb[
        valid
    ].astype(np.float32)

    colors = np.clip(
        colors,
        0.0,
        1.0,
    )

    return points, colors

