def plot_point_cloud(
    points,
    colors,
    title,
    save_path=None,
    max_points=60000,
    elevation=20,
    azimuth=-90,
):
    """
    Matplotlib으로 pseudo point cloud를 시각화합니다.
    """

    if len(points) > max_points:
        indices = np.linspace(
            0,
            len(points) - 1,
            max_points,
            dtype=int,
        )

        points = points[indices]
        colors = colors[indices]

    figure = plt.figure(
        figsize=(10, 8)
    )

    axis = figure.add_subplot(
        111,
        projection="3d",
    )

    axis.scatter(
        points[:, 0],
        points[:, 2],
        -points[:, 1],
        c=colors,
        s=0.3,
    )

    axis.set_title(title)
    axis.set_xlabel("X")
    axis.set_ylabel("Z")
