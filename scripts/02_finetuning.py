# 실제 Fine-tunint 설정
# 현재 데이터 규모 Train = 500 / Validation = 100 / Test = 100
NUM_EPOCHS = 20
EARLY_STOPPING_PATIENCE = 5
MIN_DELTA = 1e-4

# 실제 학습 실행
import json
import time
import pandas as pd
from tqdm.auto import tqdm

history = {
    "epoch": [],
    "train_loss": [],
    "val_loss": [],
    "learning_rate": [],
    "epoch_seconds": [],
}

best_val_loss = float("inf")
best_epoch = 0
epochs_without_improvement = 0

epoch_progress = tqdm(
    range(1, NUM_EPOCHS + 1),
    desc="Fine-tuning",
    unit="epoch",
)

for epoch in range(1, NUM_EPOCHS + 1):
    epoch_start = time.time()

    print(f"\nEpoch {epoch:02d}/{NUM_EPOCHS:02d}")

    train_result = training_utils.train_one_epoch(
        model=model,
        dataloader=train_loader,
        optimizer=optimizer,
        image_processor=image_processor,
        device=config_utils.DEVICE,
        gradient_clip_norm=(
            config_utils.GRADIENT_CLIP_NORM
        ),
        max_batches=None,
    )

    val_result = training_utils.validate_one_epoch(
        model=model,
        dataloader=val_loader,
        image_processor=image_processor,
        device=config_utils.DEVICE,
        max_batches=None,
    )

    train_loss = float(train_result["loss"])
    val_loss = float(val_result["loss"])

    scheduler.step(val_loss)

    current_lr = float(
        optimizer.param_groups[0]["lr"]
    )

    epoch_seconds = (
        time.time() - epoch_start
    )

    history["epoch"].append(epoch)
    history["train_loss"].append(train_loss)
    history["val_loss"].append(val_loss)
    history["learning_rate"].append(current_lr)
    history["epoch_seconds"].append(epoch_seconds)

    # --------------------------------------------------------
    # Best checkpoint 판정
    # --------------------------------------------------------
    improved =val_loss < best_val_loss - MIN_DELTA

    if improved:
        best_val_loss = val_loss
        best_epoch = epoch
        epochs_without_improvement = 0

        training_utils.save_checkpoint(
            model=model,
            optimizer=optimizer,
            scheduler=scheduler,
            epoch=epoch,
            train_loss=train_loss,
            val_loss=val_loss,
            checkpoint_path=BEST_CHECKPOINT_PATH,
            extra_state={
                "best_epoch": best_epoch,
                "best_val_loss": best_val_loss,
                "history": history,
                "model_name": (
                    config_utils.METRIC_MODEL_NAME
                ),
                "backbone_frozen": True,
            },
        )

        checkpoint_message = "Best model 저장"

    else:
        epochs_without_improvement += 1

        print(
            "Validation improvement 없음: "
            f"{epochs_without_improvement}/"
            f"{EARLY_STOPPING_PATIENCE}"
        )

    # 매 epoch마다 마지막 상태 저장
    training_utils.save_checkpoint(
        model=model,
        optimizer=optimizer,
        scheduler=scheduler,
        epoch=epoch,
        train_loss=train_loss,
        val_loss=val_loss,
        checkpoint_path=LAST_CHECKPOINT_PATH,
        extra_state={
            "best_epoch": best_epoch,
            "best_val_loss": best_val_loss,
            "history": history,
            "model_name": config_utils.METRIC_MODEL_NAME,
            "backbone_frozen": True,
        },
    )

    # 로그도 매 epoch 저장
    history_df = pd.DataFrame(history)

    history_df.to_csv(
        FINETUNE_LOG_DIR / "training_history.csv",
        index=False,
        encoding="utf-8-sig",
    )

    with open(
        FINETUNE_LOG_DIR / "training_history.json",
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            history,
            file,
            ensure_ascii=False,
            indent=2,
        )

    epoch_progress.set_postfix(
        train=f"{train_loss:.4f}",
        val=f"{val_loss:.4f}",
        lr=f"{current_lr:.2e}",
        best=f"{best_val_loss:.4f}",
        )

    tqdm.write(
        f"Train loss : {train_loss:.6f}\n"
        f"Val loss   : {val_loss:.6f}\n"
        f"LR         : {current_lr:.8f}\n"
        f"Time       : {epoch_seconds / 60:.2f}분\n"
        f"Status     : {checkpoint_message}"
    )

    if (
        epochs_without_improvement
        >= EARLY_STOPPING_PATIENCE
    ):
        print(
            "\nEarly stopping 실행: "
            f"Epoch {epoch}"
        )
        break

print("Fine-tuning 종료")
print("Best epoch   :", best_epoch)
print("Best val loss:", best_val_loss)
print("Best model   :", BEST_CHECKPOINT_PATH)

