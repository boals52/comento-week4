"""```
RGB Image
      │
      ▼
Dinov2 Backbone        ← 특징(feature) 추출
      │
      ▼
DepthAnything Neck     ← 여러 feature를 융합
      │
      ▼
Depth Head             ← depth map 생성
```

**Backbone(Dinov2)**

이미 대규모 데이터로 학습된 Vision Transformer

fine-tuning 시 : 여기를 크게 학습 시키면 학습 시간 증가 & GPU 메모리 증가 & 작은 데이터셋에서 성능 저하

**Neck(DepthAnythingNeck)**

Depth Anything에서 사용하는 여러 feature map을 depth estimation에 적합하게 합치는 부분

fine-tuning 시 : 학습

**Head(DepthAnythingDepthEstimationHead)**

최종 depth map 생성

fint-tuning 시 : 학습
"""

