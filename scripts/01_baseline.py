# Ground Truth까지 함께 불러오는 함수
def load_kitti_sample(pair, max_depth=80.0):
    """
    KITTI RGB 및 Ground Truth depth를 불러옵니다.
    """

    rgb_path = Path(pair["rgb"])
    depth_path = Path(pair["depth"])

    if not rgb_path.exists():
        raise FileNotFoundError(
            f"RGB 파일이 없습니다: {rgb_path}"
        )

    if not depth_path.exists():
        raise FileNotFoundError(
            f"Depth 파일이 없습니다: {depth_path}"
        )

    with Image.open(rgb_path) as image:
        rgb_image = image.convert("RGB")

    with Image.open(depth_path) as depth_image:
        depth_raw = np.array(
            depth_image,
            dtype=np.uint16,
        )

    depth_gt = (
        depth_raw.astype(np.float32)
        / 256.0
    )

    valid_mask = (
        (depth_gt > 0.0)
        & (depth_gt <= max_depth)
        & np.isfinite(depth_gt)
    )

    return {
        "rgb_image": rgb_image,
        "depth_gt": depth_gt,
        "valid_mask": valid_mask,
        "rgb_path": rgb_path,
        "depth_path": depth_path,
        "sequence": pair.get("sequence", ""),
        "frame": pair.get("frame", ""),
    }

