# 정확한 Global Metric 계산
# 저장된 prediction을 다시 읽어 모든 유효 픽셀의 오차 합을 누적합
# 메모리에 모든 픽셀 한꺼번에 올리지 않아서 안전

def compute_global_depth_metrics(
    pairs,
    prediction_dir,
    max_depth=80.0,
    min_depth=1e-3,
):
    """
    여러 이미지의 유효 픽셀 통계를 누적하여
    정확한 global depth metrics를 계산합니다.
    """

    valid_pixel_count = 0

    absolute_error_sum = 0.0
    squared_error_sum = 0.0
    abs_rel_sum = 0.0
    sq_rel_sum = 0.0

    delta_1_count = 0
    delta_2_count = 0
    delta_3_count = 0

    for sample_index, pair in enumerate(pairs):
        sample = load_kitti_sample(
            pair=pair,
            max_depth=max_depth,
        )

        prediction_path = (
            prediction_dir
            / (
                f"sample_{sample_index:03d}"
                "_pred_metric.npy"
            )
        )

        if not prediction_path.exists():
            raise FileNotFoundError(
                f"Prediction 파일이 없습니다: "
                f"{prediction_path}"
            )

        prediction = np.load(
            prediction_path
        ).astype(np.float64)

        ground_truth = sample[
            "depth_gt"
        ].astype(np.float64)

        valid_mask = (
            sample["valid_mask"]
            & np.isfinite(ground_truth)
            & np.isfinite(prediction)
            & (ground_truth > min_depth)
            & (ground_truth <= max_depth)
        )

        gt = ground_truth[valid_mask]

        pred = np.clip(
            prediction[valid_mask],
            min_depth,
            max_depth,
        )

        error = pred - gt
        absolute_error = np.abs(error)
        squared_error = error ** 2

        ratio = np.maximum(
            gt / pred,
            pred / gt,
        )

        current_count = gt.size

        valid_pixel_count += current_count
        absolute_error_sum += absolute_error.sum()
        squared_error_sum += squared_error.sum()
        abs_rel_sum += (
            absolute_error / gt
        ).sum()
        sq_rel_sum += (
            squared_error / gt
        ).sum()

        delta_1_count += np.sum(
            ratio < 1.25
        )
        delta_2_count += np.sum(
            ratio < 1.25 ** 2
        )
        delta_3_count += np.sum(
            ratio < 1.25 ** 3
        )

    if valid_pixel_count == 0:
        raise ValueError(
            "전체 유효 픽셀 수가 0입니다."
        )

    return {
        "sample_count": len(pairs),
        "valid_pixel_count": int(
            valid_pixel_count
        ),
        "mae": float(
            absolute_error_sum
            / valid_pixel_count
        ),
        "rmse": float(
            np.sqrt(
                squared_error_sum
                / valid_pixel_count
            )
        ),
        "abs_rel": float(
            abs_rel_sum
            / valid_pixel_count
        ),
        "sq_rel": float(
            sq_rel_sum
            / valid_pixel_count
        ),
        "delta_1": float(
            delta_1_count
            / valid_pixel_count
        ),
        "delta_2": float(
            delta_2_count
            / valid_pixel_count
        ),
        "delta_3": float(
            delta_3_count
            / valid_pixel_count
        ),
    }


