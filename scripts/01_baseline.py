def resolve_saved_path(
    saved_path,
    current_dataset_root,
):
    """
    JSON에 저장된 경로를 현재 dataset_root 기준으로 복원합니다.

    상대 경로인 경우:
        dataset_root / saved_path

    과거 절대 경로인 경우:
        경로 안의 train 또는 test 이후 부분을 사용
    """
    saved_path = Path(saved_path)

    # 일반적으로 JSON에는 상대 경로가 저장되어 있음
    if not saved_path.is_absolute():
        return (
            current_dataset_root
            / saved_path
        )

    # 절대 경로로 저장된 경우 train/test부터 추출
    path_parts = saved_path.parts

    for split_name in ["train", "test"]:
        if split_name in path_parts:
            split_index = path_parts.index(
                split_name
            )

            relative_path = Path(
                *path_parts[split_index:]
            )

            return (
                current_dataset_root
                / relative_path
            )

    raise ValueError(
        "저장된 경로에서 train/test를 "
        f"찾을 수 없습니다: {saved_path}"
    )


def restore_pairs(
    saved_pairs,
    current_dataset_root,
):
    restored_pairs = []

    for item in saved_pairs:
        restored_item = {
            "rgb": resolve_saved_path(
                item["rgb"],
                current_dataset_root,
            ),
            "depth": resolve_saved_path(
                item["depth"],
                current_dataset_root,
            ),
            "sequence": item.get(
                "sequence",
                "",
            ),
            "frame": item.get(
                "frame",
                "",
            ),
        }

        restored_pairs.append(
            restored_item
        )

    return restored_pairs


