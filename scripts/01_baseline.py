# 단일 이미지 추론 함수

def predict_relative_depth(
    rgb_input,
    model,
    image_processor,
    device,
):
    """
    Depth Anything V2 relative depth 추론 함수

    Parameters
    ----------
    rgb_input:
        PIL.Image 또는 이미지 파일 경로

    model:
        AutoModelForDepthEstimation 모델

    image_processor:
        AutoImageProcessor 객체

    device:
        torch.device("cuda") 또는 torch.device("cpu")

    Returns
    -------
    result: dict
        {
            "rgb_image": 원본 PIL 이미지,
            "predicted_depth": 원본 크기로 복원된 numpy 배열,
            "raw_prediction_shape": 모델 원본 출력 크기,
            "original_size": (width, height)
        }
    """

    # --------------------------------------------------------
    # 1. RGB 이미지 준비
    # --------------------------------------------------------
    if isinstance(rgb_input, (str, Path)):
        rgb_path = Path(rgb_input)

        if not rgb_path.exists():
            raise FileNotFoundError(
                f"RGB 이미지를 찾을 수 없습니다: {rgb_path}"
            )

        with Image.open(rgb_path) as image:
            rgb_image = image.convert("RGB")

    elif isinstance(rgb_input, Image.Image):
        rgb_image = rgb_input.convert("RGB")

    else:
        raise TypeError(
            "rgb_input은 파일 경로 또는 PIL.Image여야 합니다."
        )

    original_width, original_height = rgb_image.size

    # --------------------------------------------------------
    # 2. 모델 입력 전처리
    # --------------------------------------------------------
    inputs = image_processor(
        images=rgb_image,
        return_tensors="pt",
    )

    inputs = {
        key: value.to(device)
        for key, value in inputs.items()
    }

    # --------------------------------------------------------
    # 3. 모델 추론
    # --------------------------------------------------------
    model.eval()

    with torch.inference_mode():
        outputs = model(**inputs)

    predicted_depth = outputs.predicted_depth

    raw_prediction_shape = tuple(
        predicted_depth.shape
    )

    # --------------------------------------------------------
    # 4. 원본 이미지 크기로 복원
    # --------------------------------------------------------
    prediction_resized = F.interpolate(
        predicted_depth.unsqueeze(1),
        size=(
            original_height,
            original_width,
        ),
        mode="bicubic",
        align_corners=False,
    )

    prediction_resized = (
        prediction_resized
        .squeeze(0)
        .squeeze(0)
        .detach()
        .cpu()
        .numpy()
        .astype(np.float32)
    )

    # --------------------------------------------------------
    # 5. 결과 검증
    # --------------------------------------------------------
    if prediction_resized.shape != (
        original_height,
        original_width,
    ):
        raise ValueError(
            "예측 결과가 원본 이미지 크기와 일치하지 않습니다."
        )

    if not np.isfinite(prediction_resized).all():
        raise ValueError(
            "예측 결과에 NaN 또는 Inf가 포함되어 있습니다."
        )

    if (
        prediction_resized.max()
        <= prediction_resized.min()
    ):
        raise ValueError(
            "예측 결과가 단일 값으로 구성되어 있습니다."
        )

    return {
        "rgb_image": rgb_image,
        "predicted_depth": prediction_resized,
        "raw_prediction_shape": raw_prediction_shape,
        "original_size": (
            original_width,
            original_height,
        ),
    }

