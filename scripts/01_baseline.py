class KITTIDepthDataset(Dataset):
    def __init__(
        self,
        pairs,
        image_size=(518, 518),
        max_depth=80.0,
    ):
        self.pairs = pairs
        self.image_size = tuple(
            image_size
        )
        self.max_depth = float(
            max_depth
        )

    def __len__(self):
        return len(self.pairs)

    def __getitem__(self, index):
        pair = self.pairs[index]

        rgb_path = Path(pair["rgb"])
        depth_path = Path(pair["depth"])

        # --------------------------------------------
        # RGB 이미지 로드
        # --------------------------------------------
        with Image.open(rgb_path) as image:
            image = image.convert("RGB")

            image = TF.resize(
                image,
                size=list(self.image_size),
                interpolation=(
                    InterpolationMode.BILINEAR
                ),
                antialias=True,
            )

            image_tensor = TF.to_tensor(
                image
            )

        # --------------------------------------------
        # KITTI Depth 로드
        # uint16 값 / 256 = meter
        # --------------------------------------------
        with Image.open(depth_path) as depth_image:
            depth_raw = np.array(
                depth_image,
                dtype=np.uint16,
            )

        depth_m = (
            depth_raw.astype(np.float32)
            / 256.0
        )

        valid_mask = (
            (depth_m > 0.0)
            & (depth_m <= self.max_depth)
            & np.isfinite(depth_m)
        )

        depth_tensor = torch.from_numpy(
            depth_m
        ).unsqueeze(0)

        mask_tensor = torch.from_numpy(
            valid_mask.astype(np.float32)
        ).unsqueeze(0)

        # --------------------------------------------
        # Depth / mask resize
        # [1,H,W] → [1,1,H,W] → resize
        # --------------------------------------------
        depth_tensor = F.interpolate(
            depth_tensor.unsqueeze(0),
            size=self.image_size,
            mode="nearest",
        ).squeeze(0)

        mask_tensor = F.interpolate(
            mask_tensor.unsqueeze(0),
            size=self.image_size,
            mode="nearest",
        ).squeeze(0).bool()

        # 유효하지 않은 depth 값은 0으로 정리
        depth_tensor = torch.where(
            mask_tensor,
            depth_tensor,
            torch.zeros_like(
                depth_tensor
            ),
        )

        return {
            "image": image_tensor,
            "depth": depth_tensor,
            "valid_mask": mask_tensor,
            "rgb_path": str(rgb_path),
            "depth_path": str(depth_path),
            "sequence": pair["sequence"],
            "frame": pair["frame"],
        }


