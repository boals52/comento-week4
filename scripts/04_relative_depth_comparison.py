"""MiDaS 계열 출력은 값이 클수록 가까운 영역으로 나타내는 inverse-depth 성격 -> 같은 방향으로 시각적으로 비교하려면 값을 반전해 사용"""

def invert_and_normalize_relative_depth(
    relative_depth: np.ndarray,
) -> np.ndarray:
    """
    MiDaS inverse-depth 성격의 출력을 반전하고
    0~1 범위로 정규화합니다.

    0에 가까울수록 상대적으로 가까움,
    1에 가까울수록 상대적으로 멂으로 표시합니다.
    """

    relative_depth = np.asarray(
        relative_depth,
        dtype=np.float32,
    )

    finite_mask = np.isfinite(
        relative_depth
    )

    if not finite_mask.any():
        raise ValueError(
            "유효한 MiDaS 출력값이 없습니다."
        )

    minimum = float(
        relative_depth[
            finite_mask
        ].min()
    )

    maximum = float(
        relative_depth[
            finite_mask
        ].max()
    )

    if maximum <= minimum:
        raise ValueError(
            "MiDaS 출력 범위가 유효하지 않습니다."
        )

    normalized_inverse_depth = (
        relative_depth - minimum
    ) / (
        maximum - minimum
    )

    normalized_relative_distance = (
        1.0 - normalized_inverse_depth
    )

    return normalized_relative_distance.astype(
        np.float32
    )

