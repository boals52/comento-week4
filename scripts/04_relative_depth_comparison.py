# MiDaS Point Cloud 생성 함수
def relative_depth_to_pseudo_point_cloud(
    relative_distance: np.ndarray,
    rgb: np.ndarray,
    stride: int = 2,
    depth_scale: float = 40.0,
    minimum_depth: float = 1.0,
):
    """
    0~1 상대 거리값으로 pseudo point cloud를 생성합니다.

    relative_distance:
        0에 가까울수록 가까움
        1에 가까울수록 멂

    출력 Z는 시각화를 위한 임의 스케일이며
    실제 미터 단위가 아닙니다.
    """

    if relative_distance.ndim != 2:
        raise ValueError(
            "relative_distance는 [H, W]여야 합니다."
        )

    if (
        rgb.ndim != 3
        or rgb.shape[2] != 3
    ):
        raise ValueError(
            "rgb는 [H, W, 3]이어야 합니다."
        )

    if (
        rgb.shape[:2]
        != relative_distance.shape
    ):
        raise ValueError(
            "RGB와 상대 깊이 해상도가 다릅니다."
        )

    height, width = (
        relative_distance.shape
    )

    focal_length = float(
        max(height, width)
    )

    fx = focal_length
    fy = focal_length
    cx = (width - 1) / 2.0
    cy = (height - 1) / 2.0

    v, u = np.mgrid[
        0:height:stride,
        0:width:stride,
    ]

    sampled_relative = relative_distance[
        0:height:stride,
        0:width:stride,
    ]

    sampled_rgb = rgb[
        0:height:stride,
        0:width:stride,
    ]

    z = (
        minimum_depth
        + sampled_relative
        * depth_scale
    )

    x = (
        (u - cx)
        * z
        / fx
    )

    y = (
        (v - cy)
        * z
        / fy
    )

    points = np.column_stack(
        [
            x.ravel(),
            y.ravel(),
            z.ravel(),
        ]
    ).astype(np.float32)

    colors = (
        sampled_rgb
        .reshape(-1, 3)
        .astype(np.float32)
    )

    return points, colors

