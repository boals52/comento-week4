def generate_virtual_depth(
    rgb_image: np.ndarray,
) -> np.ndarray:
    """
    RGB 이미지의 grayscale 밝기값을
    가상의 상대 깊이값으로 사용합니다.

    Parameters
    ----------
    rgb_image : np.ndarray
        [H, W, 3] RGB 이미지, 범위 0~1 또는 0~255

    Returns
    -------
    np.ndarray
        [H, W] uint8 virtual depth map
    """

    if rgb_image is None:
        raise ValueError(
            "입력된 이미지가 없습니다."
        )

    rgb_image = np.asarray(rgb_image)

    if (
        rgb_image.ndim != 3
        or rgb_image.shape[2] != 3
    ):
        raise ValueError(
            "RGB 이미지는 [H, W, 3] 형태여야 합니다."
        )

    if rgb_image.max() <= 1.0:
        rgb_uint8 = np.clip(
            rgb_image * 255.0,
            0,
            255,
        ).astype(np.uint8)
    else:
        rgb_uint8 = np.clip(
            rgb_image,
            0,
            255,
        ).astype(np.uint8)

    virtual_depth = cv2.cvtColor(
        rgb_uint8,
        cv2.COLOR_RGB2GRAY,
    )

    return virtual_depth

