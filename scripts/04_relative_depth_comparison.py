# Point cloud 생성
def virtual_depth_to_point_cloud(
    virtual_depth: np.ndarray,
    rgb: np.ndarray,
    stride: int = 2,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Virtual Depth를 brightness-based pseudo point cloud로 변환합니다.

    X, Y: 픽셀 좌표
    Z: grayscale 밝기값
    colors: 원본 RGB 색상
    """

    if virtual_depth.ndim != 2:
        raise ValueError(
            "virtual_depth는 [H, W] 형태여야 합니다."
        )

    if rgb.ndim != 3 or rgb.shape[2] != 3:
        raise ValueError(
            "rgb는 [H, W, 3] 형태여야 합니다."
        )

    if rgb.shape[:2] != virtual_depth.shape:
        raise ValueError(
            "RGB와 Virtual Depth 해상도가 일치하지 않습니다."
        )

    height, width = virtual_depth.shape

    y_coordinates, x_coordinates = np.mgrid[
        0:height:stride,
        0:width:stride,
    ]

    sampled_depth = virtual_depth[
        0:height:stride,
        0:width:stride,
    ].astype(np.float32)

    sampled_rgb = rgb[
        0:height:stride,
        0:width:stride,
    ].astype(np.float32)

    points = np.column_stack(
        [
            x_coordinates.ravel(),
            y_coordinates.ravel(),
            sampled_depth.ravel(),
        ]
    ).astype(np.float32)

    colors = sampled_rgb.reshape(
        -1,
        3,
    )

    return points, colors

def rgb_array_to_plotly_colors(
    colors: np.ndarray,
):
    """
    RGB 배열을 Plotly에서 사용할
    rgb(r,g,b) 문자열로 변환합니다.
    """

    colors = np.asarray(
        colors,
        dtype=np.float32,
    )

    if colors.max() <= 1.0:
        colors = colors * 255.0

    colors = np.clip(
        colors,
        0,
        255,
    ).astype(np.uint8)

    plotly_colors = [
        f"rgb({r},{g},{b})"
        for r, g, b in colors
    ]

    return plotly_colors

