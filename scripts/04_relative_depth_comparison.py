# Point Cloud 변환 함수

def metric_depth_to_pseudo_point_cloud(
    depth: np.ndarray,
    rgb: np.ndarray,
    min_depth: float = 0.1,
    max_depth: float = 80.0,
    stride: int = 2,
    focal_length: float | None = None,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Metric depth map을 근사 카메라 내부 파라미터로
    pseudo point cloud로 변환합니다.

    주의:
    calibration 파일이 없으므로 정밀한 3D 복원은 아닙니다.
    Z값 자체는 모델이 예측한 metric depth(m)를 사용합니다.
    """

    depth = np.asarray(depth, dtype=np.float32)
    rgb = np.asarray(rgb, dtype=np.float32)

    if depth.ndim != 2:
        raise ValueError(
            f"depth는 [H, W]여야 합니다. 입력: {depth.shape}"
        )

    if rgb.ndim != 3 or rgb.shape[2] != 3:
        raise ValueError(
            f"rgb는 [H, W, 3]이어야 합니다. 입력: {rgb.shape}"
        )

    if rgb.shape[:2] != depth.shape:
        raise ValueError(
            "RGB와 depth 해상도가 일치하지 않습니다."
        )

    height, width = depth.shape

    if focal_length is None:
        focal_length = float(max(height, width))

    fx = focal_length
    fy = focal_length
    cx = (width - 1) / 2.0
    cy = (height - 1) / 2.0

    v, u = np.mgrid[
        0:height:stride,
        0:width:stride,
    ]

    sampled_depth = depth[
        0:height:stride,
        0:width:stride,
    ]

    sampled_rgb = rgb[
        0:height:stride,
        0:width:stride,
    ]

    valid = (
        np.isfinite(sampled_depth)
        & (sampled_depth >= min_depth)
        & (sampled_depth <= max_depth)
    )

    z = sampled_depth[valid]

    x = (
        (u[valid] - cx)
        * z
        / fx
    )

    y = (
        (v[valid] - cy)
        * z
        / fy
    )

    points = np.stack(
        [x, y, z],
        axis=1,
    ).astype(np.float32)

    colors = sampled_rgb[
        valid
    ].astype(np.float32)

    colors = np.clip(
        colors,
        0.0,
        1.0,
    )

    return points, colors

