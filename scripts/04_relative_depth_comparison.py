from PIL import Image
import torch.nn.functional as F


def predict_midas_relative_depth(
    image_tensor: torch.Tensor,
    model,
    image_processor,
    device,
) -> np.ndarray:
    """
    [3, H, W] RGB Tensor에서 MiDaS 상대 깊이를 추론합니다.

    반환값
    -------
    np.ndarray
        원본 입력과 동일한 [H, W] 크기의 float32 상대 깊이 배열
    """

    if image_tensor.ndim != 3:
        raise ValueError(
            "image_tensor는 [3, H, W] 형태여야 합니다."
        )

    if image_tensor.shape[0] != 3:
        raise ValueError(
            "RGB 3채널 이미지가 필요합니다."
        )

    height, width = image_tensor.shape[-2:]

    rgb_array = (
        image_tensor
        .detach()
        .cpu()
        .permute(1, 2, 0)
        .numpy()
    )

    rgb_uint8 = np.clip(
        rgb_array * 255.0,
        0,
        255,
    ).astype(np.uint8)

    pil_image = Image.fromarray(
        rgb_uint8,
        mode="RGB",
    )

    inputs = image_processor(
        images=pil_image,
        return_tensors="pt",
    )

    pixel_values = inputs[
        "pixel_values"
    ].to(device)

    with torch.inference_mode():
        outputs = model(
            pixel_values=pixel_values
        )

        predicted_depth = (
            outputs.predicted_depth
        )

        predicted_depth = F.interpolate(
            predicted_depth.unsqueeze(1),
            size=(height, width),
            mode="bicubic",
            align_corners=False,
        )

    return (
        predicted_depth[
            0,
            0,
        ]
        .detach()
        .cpu()
        .numpy()
        .astype(np.float32)
    )

